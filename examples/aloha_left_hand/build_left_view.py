"""Build the left-arm-only ("left") views of hungho77/aloha-left-hand-3task (user decision 2026-11-26).

The right arm never moves in this data, so it is removed and the set is trained as a single arm (as the SO101 runs):
  * action / observation.state / observation.velocity / observation.effort: the 7 left dims only
    (left_waist, left_shoulder, left_elbow, left_forearm_roll, left_wrist_angle, left_wrist_rotate, left_gripper);
    values unchanged.
  * cameras: observation.images.color.high + observation.images.color.wrist_left; wrist_right (the idle right arm's
    camera) is dropped.

Outputs (sources are only read):
  1. LeRobot v2.1 view  DATA_ZOO/aloha_left_hand_merged_v21_left/hungho77/aloha-left-hand-3task
     parquet rewritten, videos of the 2 kept cameras hard-linked (symlink fallback, no re-encode), meta/info.json
     features + total_videos updated, episodes_stats.jsonl / stats.json sliced to the kept dims / features (the
     statistics are per dim, so slicing is exact).
  2. GR00T view         DATA_ZOO/aloha_left_hand_merged_v21_left_gr00t/hungho77/aloha-left-hand-3task
     data/ videos/ symlinked to (1), meta copied from (1) + modality.json (single_arm 0..6, gripper 6..7,
     video high / wrist_left). GR00T's stats.json / relative_stats.json are then generated by gr00t.data.stats.
"""

import json
import os
from pathlib import Path
import shutil

import numpy as np
import pyarrow as pa
import pyarrow.parquet as pq

ZOO = Path("/mnt/data/sftp/data/hunght23/DATA_ZOO")
REPO = "hungho77/aloha-left-hand-3task"
SRC = ZOO / "aloha_left_hand_merged_v21" / REPO
DST = ZOO / "aloha_left_hand_merged_v21_left" / REPO
DST_GR00T = ZOO / "aloha_left_hand_merged_v21_left_gr00t" / REPO
VEC = ("action", "observation.state", "observation.velocity", "observation.effort")
DROP_VIDEO = "observation.images.color.wrist_right"
N = 7

MODALITY = {
    "state": {"single_arm": {"start": 0, "end": 6}, "gripper": {"start": 6, "end": 7}},
    "action": {"single_arm": {"start": 0, "end": 6}, "gripper": {"start": 6, "end": 7}},
    "video": {
        "high": {"original_key": "observation.images.color.high"},
        "wrist_left": {"original_key": "observation.images.color.wrist_left"},
    },
    "annotation": {"human.task_description": {"original_key": "task_index"}},
}


def slice_stats(st: dict) -> dict:
    return {k: (v if k == "count" else v[:N]) for k, v in st.items()}


def link(src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    try:
        os.link(src, dst)
    except OSError:
        os.symlink(src, dst)


def main() -> int:
    if DST.exists() or DST_GR00T.exists():
        print(f"refusing to overwrite existing {DST} / {DST_GR00T}")
        return 1
    info = json.loads((SRC / "meta/info.json").read_text())
    files = sorted((SRC / "data").glob("chunk-*/episode_*.parquet"))
    assert len(files) == info["total_episodes"] == 249, len(files)

    # parquet
    frames = 0
    for f in files:
        t = pq.read_table(f)
        for k in VEC:
            v = np.stack(t[k].to_numpy(zero_copy_only=False)).astype(np.float32)
            assert v.shape[1] == 14
            i = t.schema.get_field_index(k)
            t = t.set_column(i, t.schema.field(i), pa.array(list(v[:, :N]), type=t.schema.field(i).type))
        t = t.replace_schema_metadata(None)  # the pandas metadata describes the old frame; not needed
        out = DST / f.relative_to(SRC)
        out.parent.mkdir(parents=True, exist_ok=True)
        pq.write_table(t, out)
        frames += t.num_rows
    assert frames == info["total_frames"]

    # videos (2 of 3 cameras)
    n_vid = 0
    for v in sorted((SRC / "videos").rglob("*.mp4")):
        if v.parent.name == DROP_VIDEO:
            continue
        link(v, DST / v.relative_to(SRC))
        n_vid += 1

    # meta
    (DST / "meta").mkdir(parents=True, exist_ok=True)
    for name in ("episodes.jsonl", "tasks.jsonl"):
        shutil.copy2(SRC / "meta" / name, DST / "meta" / name)
    feats = info["features"]
    del feats[DROP_VIDEO]
    for k in VEC:
        feats[k]["shape"] = [N]
        names = feats[k]["names"]
        key = next(iter(names))
        names[key] = names[key][:N]
        assert names[key][-1] == "left_gripper", names
    info["total_videos"] = n_vid
    assert n_vid == 2 * info["total_episodes"]
    (DST / "meta/info.json").write_text(json.dumps(info, indent=4))

    lines = []
    for x in (SRC / "meta/episodes_stats.jsonl").read_text().splitlines():
        if not x.strip():
            continue
        e = json.loads(x)
        e["stats"].pop(DROP_VIDEO)
        for k in VEC:
            e["stats"][k] = slice_stats(e["stats"][k])
        lines.append(json.dumps(e))
    (DST / "meta/episodes_stats.jsonl").write_text("\n".join(lines) + "\n")
    stats = json.loads((SRC / "meta/stats.json").read_text())
    stats.pop(DROP_VIDEO)
    for k in VEC:
        stats[k] = slice_stats(stats[k])
    (DST / "meta/stats.json").write_text(json.dumps(stats, indent=4))

    # GR00T view
    (DST_GR00T / "meta").mkdir(parents=True)
    os.symlink(DST / "data", DST_GR00T / "data")
    os.symlink(DST / "videos", DST_GR00T / "videos")
    for name in ("info.json", "episodes.jsonl", "tasks.jsonl", "episodes_stats.jsonl"):
        shutil.copy2(DST / "meta" / name, DST_GR00T / "meta" / name)
    (DST_GR00T / "meta/modality.json").write_text(json.dumps(MODALITY, indent=4))

    # checks: kept dims identical to the source
    for f in files[::25]:
        a, b = pq.read_table(f), pq.read_table(DST / f.relative_to(SRC))
        for k in VEC:
            x = np.stack(a[k].to_numpy(zero_copy_only=False))
            y = np.stack(b[k].to_numpy(zero_copy_only=False))
            assert y.shape[1] == N, (f, k)
            assert np.array_equal(x[:, :N], y), (f, k)
    print(f"wrote {DST} ({len(files)} episodes, {frames} frames, {n_vid} videos) and {DST_GR00T}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
